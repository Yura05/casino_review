def nav_items(lang: str) -> list[dict[str, str]]:
    """Lista metod do menu (slug + zlokalizowana nazwa)."""
    return [{"slug": slug, "name": m[f"name_{lang}"]} for slug, m in PAYMENT_METHODS.items()]


def get_method(slug: str, lang: str) -> dict | None:
    """Zlokalizowane dane jednej metody (do strony /oplata/{slug}/)."""
    m = PAYMENT_METHODS.get(slug)
    if m is None:
        return None
    return {
        "slug": slug,
        "name": m[f"name_{lang}"],
        "intro": m.get(f"intro_{lang}"),
        "steps": m.get(f"steps_{lang}", []),
        "tokens": m["tokens"],
    }
