def run() -> None:
    db = SessionLocal()
    try:
        # Pobierz wszystkie kategorie zakladow (z seeda) do mapy slug->obiekt.
        cats = {bc.slug: bc for bc in db.scalars(select(BettingCategory)).all()}

        # Sprawdz, czy seed kategorii byl uruchomiony.
        missing = _CAT_SLUGS - set(cats.keys())
        if missing:
            print(f"ERROR: brak kategorii zakladow w bazie: {sorted(missing)}. Najpierw uruchom seed.")
            return

        added = 0
        skipped = 0
        for d in _BOOKMAKERS_DATA:
            slug = d["slug"]
            existing = db.scalars(select(Bookmaker).where(Bookmaker.slug == slug)).first()
            if existing is not None:
                print(f"SKIP: {slug} juz istnieje")
                skipped += 1
                continue

            b = Bookmaker(
                slug=slug,
                name=d["name"],
                rating=d["rating"],
                license=d["license"],
                license_number=d["license_number"],
                established=d["established"],
                min_deposit=d["min_deposit"],
                payment_methods=d["payment_methods"],
                affiliate_link=f"https://example.com/go/{slug}",
                bonus_uk=d["bonus_uk"],
                bonus_ru=d["bonus_ru"],
                description_uk=d["description_uk"],
                description_ru=d["description_ru"],
                pros_uk=d["pros_uk"],
                pros_ru=d["pros_ru"],
                cons_uk=d["cons_uk"],
                cons_ru=d["cons_ru"],
                overview_uk=d["overview_uk"],
                overview_ru=d["overview_ru"],
                verdict_uk=d["verdict_uk"],
                verdict_ru=d["verdict_ru"],
                betting_categories=[cats[s] for s in d["cats"]],
            )
            db.add(b)
            # ASCII-only print (name moze zawierac non-ASCII w przyszlosci, ale obecnie ok).
            print(f"ADD: {slug} (rating {d['rating']})")
            added += 1

        db.commit()
        print(f"OK: dodano {added}, pominieto {skipped}")
    finally:
        db.close()


if __name__ == "__main__":
    run()
