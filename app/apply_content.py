def _apply(db, model, content: dict[str, dict[str, str]], label: str) -> int:
    updated = 0
    for slug, fields in content.items():
        row = db.scalars(select(model).where(model.slug == slug)).first()
        if row is None:
            print(f"SKIP: {label} '{slug}' not found")
            continue
        for field, value in fields.items():
            setattr(row, field, value)
        print(f"SET: {label} '{slug}' ({len(fields)} fields)")
        updated += 1
    return updated


def run() -> None:
    db = SessionLocal()
    try:
        n_bm = _apply(db, Bookmaker, BOOKMAKER_CONTENT, "bookmaker")
        n_cas = _apply(db, Casino, CASINO_CONTENT, "casino")
        db.commit()
        print(f"OK: updated {n_bm} bookmaker(s), {n_cas} casino(s)")
    finally:
        db.close()


if __name__ == "__main__":
    run()
