def run() -> None:
    db = SessionLocal()
    try:
        updated = 0
        for slug, fields in BOOKMAKER_CONTENT.items():
            bm = db.scalars(select(Bookmaker).where(Bookmaker.slug == slug)).first()
            if bm is None:
                print(f"SKIP: bookmaker '{slug}' not found")
                continue
            for field, value in fields.items():
                setattr(bm, field, value)
            print(f"SET: bookmaker '{slug}' ({len(fields)} fields)")
            updated += 1
        db.commit()
        print(f"OK: updated {updated} bookmaker(s)")
    finally:
        db.close()


if __name__ == "__main__":
    run()
